#!/usr/bin/env python3
"""Extract the four WGSL shader modules from gpu.rs, renumber @group by
binding (fields/params -> 0, materials/pec -> 1, cpml -> 2, misc -> 3),
and compute per-entry-point binding usage for minimal WebGPU layouts."""
import re, json, sys

import os
_HERE = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(_HERE, '..', '..', 'wasm', 'fdtd', 'src', 'gpu.rs')).read()

def extract(name):
    m = re.search(r'const %s: &str = r#"(.*?)"#;' % name, src, re.S)
    assert m, name
    return m.group(1)

GROUP = {}
for b in [0,2,3,4,5,6,7]: GROUP[b] = 0
for b in range(8,17): GROUP[b] = 1
for b in [1,17,18]: GROUP[b] = 2
for b in [19,20,21]: GROUP[b] = 3
GROUP[28] = 3  # tangential-damping factor buffer (SHADER_DAMP)

def renumber(wgsl):
    def sub(m):
        b = int(m.group(2))
        return '@group(%d) @binding(%d)' % (GROUP[b], b)
    return re.sub(r'@group\(0\) @binding\((\d+)\)', lambda m: '@group(%d) @binding(%s)' % (GROUP[int(m.group(1))], m.group(1)), wgsl)

# declared storage/uniform vars: name -> (binding, kind)
DECL = {}
for m in re.finditer(r'@group\(\d+\) @binding\((\d+)\) var<(\w+)(?:,\s*(\w+))?> (\w+):', src):
    b, kind, rw, name = int(m.group(1)), m.group(2), m.group(3), m.group(4)
    DECL[name] = (b, kind, rw)

def fn_bodies(wgsl):
    """name -> body text for every fn in the module."""
    out = {}
    for m in re.finditer(r'fn (\w+)\s*\(', wgsl):
        name = m.group(1)
        # find opening brace of this fn
        i = wgsl.index('{', m.end())
        depth = 0; j = i
        while True:
            c = wgsl[j]
            if c == '{': depth += 1
            elif c == '}':
                depth -= 1
                if depth == 0: break
            j += 1
        out[name] = wgsl[i:j+1]
    return out

def usage(wgsl):
    bodies = fn_bodies(wgsl)
    entries = [n for n in bodies if re.search(r'@compute[^}]*fn %s' % n, wgsl, re.S) or n in
               ('update_hx','update_hy','update_hz','update_ex','update_ey','update_ez',
                'cpml_e_x','cpml_e_y','cpml_e_z','cpml_h_x','cpml_h_y','cpml_h_z',
                'damp_ex','damp_ey','damp_ez','damp_hx','damp_hy','damp_hz',
                'wire_update','wire_deposit','pec_ex','pec_ey','pec_ez','source_step')]
    result = {}
    for e in entries:
        seen = set()
        stack = [e]
        used = set()
        while stack:
            f = stack.pop()
            if f in seen or f not in bodies: continue
            seen.add(f)
            body = bodies[f]
            for tok in re.findall(r'[A-Za-z_][A-Za-z0-9_]*', body):
                if tok in DECL: used.add(tok)
                if tok in bodies and tok != f: stack.append(tok)
        result[e] = sorted(used)
    return result

shaders = {}
usage_all = {}
for key, const in [('h','SHADER_H'), ('e','SHADER_E'), ('cpml','SHADER_CPML'), ('damp','SHADER_DAMP'), ('misc','SHADER_MISC')]:
    raw = extract(const)
    shaders[key] = renumber(raw)
    usage_all[key] = usage(raw)

# Page-side transform (same class as the @group renumbering): the PEC
# mask kernels index by gid.x alone, so a flat dispatch over a big
# component array exceeds WebGPU's 65535 workgroups-per-dimension cap
# (first hit at the 24-layer grid: ceil(26.6M/256) = 103,889). Rewrite
# the three pec entry points as grid-stride loops over a capped
# dispatch; semantics identical (each set element visited once).
def pec_stride(wgsl):
    for comp, mask in (('ex', 'pec_x'), ('ey', 'pec_y'), ('ez', 'pec_z')):
        pat = re.compile(
            r'fn pec_%s\(@builtin\(global_invocation_id\) gid: vec3<u32>\) \{\n'
            r'    let n = gid\.x;\n'
            r'    if \(n >= arrayLength\(&%s\)\) \{ return; \}\n'
            r'    if \(%s\[n\] != 0u\) \{ %s\[n\] = 0\.0; \}\n\}' % (comp, comp, mask, comp))
        rep = (
            'fn pec_%s(@builtin(global_invocation_id) gid: vec3<u32>) {\n'
            '    let total = arrayLength(&%s);\n'
            '    for (var n = gid.x; n < total; n += 16776960u) {\n'
            '        if (%s[n] != 0u) { %s[n] = 0.0; }\n'
            '    }\n}' % (comp, comp, mask, comp))
        wgsl, n = pat.subn(rep, wgsl)
        assert n == 1, 'pec_%s body not found for stride transform' % comp
    return wgsl

shaders['misc'] = pec_stride(shaders['misc'])

decl_js = {name: {'binding': b, 'kind': kind, 'rw': rw == 'read_write'} for name,(b,kind,rw) in DECL.items()}
out = []
out.append('// AUTO-GENERATED by build/gen_shaders.py from wasm/fdtd/src/gpu.rs — do not edit by hand.')
out.append('const SOLVER_SHADERS = {')
for k, v in shaders.items():
    out.append('  %s: %s,' % (k, json.dumps(v)))
out.append('};')
out.append('const SOLVER_DECL = %s;' % json.dumps(decl_js))
out.append('const SOLVER_USAGE = %s;' % json.dumps(usage_all))
open(os.path.join(_HERE, 'solver_shaders.js'),'w').write('\n'.join(out) + '\n')
for k, u in usage_all.items():
    for e, names in sorted(u.items()):
        bs = sorted(set(DECL[n][0] for n in names))
        print(k, e, 'bindings:', bs)
print('OK')
